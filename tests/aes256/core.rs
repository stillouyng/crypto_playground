#[cfg(test)]
mod tests {
    use crypto_playground::encode::core::AES;

    #[test]
    fn test_sub_bytes() {
        let aes = AES::new();
        let mut state = [
            [0x19, 0x3d, 0xe3, 0xbe],
            [0xa0, 0xf4, 0xe2, 0x2b],
            [0x9a, 0xc6, 0x8d, 0x2a],
            [0xe9, 0xf8, 0x48, 0x08],
        ];

        aes.sub_bytes(&mut state);

        assert_eq!(
            state,
            [
                [0xd4, 0x27, 0x11, 0xae],
                [0xe0, 0xbf, 0x98, 0xf1],
                [0xb8, 0xb4, 0x5d, 0xe5],
                [0x1e, 0x41, 0x52, 0x30]
            ]
        );
    }

    #[test]
    fn test_shift_rows() {
        let mut state = [
            [0x00, 0x01, 0x02, 0x03],
            [0x10, 0x11, 0x12, 0x13],
            [0x20, 0x21, 0x22, 0x23],
            [0x30, 0x31, 0x32, 0x33],
        ];
        let expected = [
            [0x00, 0x01, 0x02, 0x03],
            [0x11, 0x12, 0x13, 0x10],
            [0x22, 0x23, 0x20, 0x21],
            [0x33, 0x30, 0x31, 0x32],
        ];
        AES::new().shift_rows(&mut state);
        assert_eq!(state, expected);
    }

    #[test]
    fn test_mix_columns() {
        let aes = AES::new();

        let mut state1 = [
            [0x63, 0x63, 0x63, 0x63],
            [0x63, 0x63, 0x63, 0x63],
            [0x63, 0x63, 0x63, 0x63],
            [0x63, 0x63, 0x63, 0x63],
        ];
        let expected1 = state1.clone();
        aes.mix_columns(&mut state1);
        assert_eq!(state1, expected1);

        let mut state2 = [
            [0xDB, 0xF2, 0x01, 0x00],
            [0x13, 0x0A, 0x01, 0x00],
            [0x53, 0x22, 0x01, 0x00],
            [0x45, 0x5C, 0x01, 0x00],
        ];

        let expected2 = [
            [0x8E, 0x9F, 0x01, 0x00],
            [0x4D, 0xDC, 0x01, 0x00],
            [0xA1, 0x58, 0x01, 0x00],
            [0xBC, 0x9D, 0x01, 0x00],
        ];
        aes.mix_columns(&mut state2);
        assert_eq!(state2, expected2);
    }

    #[test]
    fn test_add_round_key_isolated() {
        let aes = AES::new();

        let mut state = [
            [0x04, 0xe0, 0x48, 0x28],
            [0x66, 0xcb, 0xf8, 0x06],
            [0x81, 0x19, 0xd3, 0x26],
            [0xe5, 0x9a, 0x7a, 0x4c],
        ];

        let round_key = [
            0xa0, 0xfa, 0xfe, 0x17, 0x88, 0x54, 0x2c, 0xb1, 0x23, 0xa3, 0x39, 0x39, 0x2a, 0x6c,
            0x76, 0x05,
        ];

        aes.add_round_key(&mut state, &round_key);

        assert_eq!(
            state,
            [
                [0xa4, 0x68, 0x6b, 0x02],
                [0x9c, 0x9f, 0x5b, 0x6a],
                [0x7f, 0x35, 0xea, 0x50],
                [0xf2, 0x2b, 0x43, 0x49]
            ]
        );
    }
}
